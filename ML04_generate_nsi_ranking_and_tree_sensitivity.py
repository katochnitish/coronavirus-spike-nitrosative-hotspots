def first_existing(df: pd.DataFrame, names: list[str]) -> str | None:
    for name in names:
        if name in df.columns:
            return name
    return None


def numeric_series(df: pd.DataFrame, name: str | None, default: float = 0.0) -> pd.Series:
    if name is None or name not in df.columns:
        return pd.Series(default, index=df.index, dtype=float)
    return pd.to_numeric(df[name], errors="coerce").astype(float)


def minmax(series: pd.Series, invert: bool = False, fill_value: float | None = None) -> pd.Series:
    x = pd.to_numeric(series, errors="coerce").astype(float)
    if x.notna().sum() == 0:
        scaled = pd.Series(np.zeros(len(x)), index=x.index, dtype=float)
    else:
        if fill_value is None:
            x = x.fillna(x.median())
        else:
            x = x.fillna(fill_value)
        xmin, xmax = x.min(), x.max()
        if np.isclose(xmax, xmin):
            scaled = pd.Series(np.zeros(len(x)), index=x.index, dtype=float)
        else:
            scaled = (x - xmin) / (xmax - xmin)
    return 1.0 - scaled if invert else scaled


def safe_mean(columns: list[pd.Series], index: pd.Index) -> pd.Series:
    valid = [col for col in columns if col is not None]
    if not valid:
        return pd.Series(0.0, index=index, dtype=float)
    mat = pd.concat(valid, axis=1)
    return mat.mean(axis=1).fillna(0.0)


def choose_label_column(df: pd.DataFrame) -> str | None:
    for col in LABEL_CANDIDATES:
        if col in df.columns:
            values = set(pd.Series(df[col]).dropna().unique())
            if values.issubset({0, 1, 0.0, 1.0, True, False}):
                return col
    return None


