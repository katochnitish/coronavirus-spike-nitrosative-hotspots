def build_feature_table(df: pd.DataFrame, label_col: str | None = None):
    available_primary = [col for col in PRIMARY_MODEL_FEATURES if col in df.columns]
    additional_components = [col for col in COMPONENT_WEIGHTS if col in df.columns]
    feature_cols = available_primary + [col for col in additional_components if col not in available_primary]

    additional_numeric = [
        col for col in df.columns
        if col not in EXCLUDE_FROM_MODEL
        and not col.startswith("_")
        and col not in feature_cols
        and pd.api.types.is_numeric_dtype(df[col])
    ]
    feature_cols.extend(additional_numeric)

    if label_col and label_col in feature_cols:
        feature_cols.remove(label_col)

    if not feature_cols:
        raise ValueError("No usable predictive features were found.")

    X = df[feature_cols].copy()
    numeric_cols = [col for col in feature_cols if pd.api.types.is_numeric_dtype(X[col])]
    categorical_cols = [col for col in feature_cols if col not in numeric_cols]
    return X, feature_cols, numeric_cols, categorical_cols


def make_preprocessor(numeric_cols: list[str], categorical_cols: list[str]) -> ColumnTransformer:
    transformers = []
    if numeric_cols:
        transformers.append((
            "numeric",
            Pipeline([
                ("imputer", SimpleImputer(strategy="median")),
                ("scaler", StandardScaler()),
            ]),
            numeric_cols,
        ))
    if categorical_cols:
        transformers.append((
            "categorical",
            Pipeline([
                ("imputer", SimpleImputer(strategy="most_frequent")),
                ("onehot", OneHotEncoder(handle_unknown="ignore")),
            ]),
            categorical_cols,
        ))
    return ColumnTransformer(transformers=transformers, remainder="drop")


def make_classifier():
    if XGBOOST_AVAILABLE:
        return xgb.XGBClassifier(
            n_estimators=250,
            max_depth=3,
            learning_rate=0.03,
            subsample=0.85,
            colsample_bytree=0.85,
            min_child_weight=2,
            reg_lambda=2.0,
            objective="binary:logistic",
            eval_metric="logloss",
            random_state=RANDOM_STATE,
        )
    return RandomForestClassifier(
        n_estimators=500,
        max_depth=5,
        min_samples_leaf=3,
        class_weight="balanced",
        random_state=RANDOM_STATE,
        n_jobs=-1,
    )


def make_regressor():
    return RandomForestRegressor(
        n_estimators=500,
        max_depth=5,
        min_samples_leaf=3,
        random_state=RANDOM_STATE,
        n_jobs=-1,
    )


def save_permutation_importance(model, X_test, y_test, feature_cols, scoring: str) -> pd.DataFrame:
    perm = permutation_importance(
        model,
        X_test,
        y_test,
        n_repeats=30,
        random_state=RANDOM_STATE,
        scoring=scoring,
    )
    importance_df = pd.DataFrame({
        "Feature": feature_cols,
        "Permutation_Importance_Mean": perm.importances_mean,
        "Permutation_Importance_SD": perm.importances_std,
    }).sort_values("Permutation_Importance_Mean", ascending=False)
    importance_df.to_csv(OUTPUT_FEATURE_IMPORTANCE, index=False)

    top_imp = importance_df.head(25).iloc[::-1]
    plt.figure(figsize=(8, max(4, len(top_imp) * 0.32)))
    plt.barh(top_imp["Feature"], top_imp["Permutation_Importance_Mean"], edgecolor="black")
    plt.xlabel(f"Permutation importance ({scoring})")
    plt.title("Tree-Based Feature Sensitivity")
    plt.tight_layout()
    plt.savefig(PLOT_FEATURE_IMPORTANCE, dpi=300)
    plt.close()
    return importance_df


# Tree-based regression to assess feature sensitivity

def run_nsi_regression(df: pd.DataFrame) -> str:
    X, feature_cols, numeric_cols, categorical_cols = build_feature_table(df)
    y = pd.to_numeric(df["NSI_Proxy_Score"], errors="coerce").values
    groups = get_groups(df)

    valid = np.isfinite(y)
    X = X.loc[valid].copy()
    y = y[valid]
    groups = groups[valid]

    model = Pipeline([
        ("preprocess", make_preprocessor(numeric_cols, categorical_cols)),
        ("model", make_regressor()),
    ])

    unique_groups = np.unique(groups)
    if len(unique_groups) >= 3:
        splitter = GroupShuffleSplit(n_splits=1, test_size=TEST_SIZE, random_state=RANDOM_STATE)
        train_idx, test_idx = next(splitter.split(X, y, groups=groups))
    else:
        rng = np.random.default_rng(RANDOM_STATE)
        indices = np.arange(len(X))
        rng.shuffle(indices)
        cut = int(len(indices) * (1.0 - TEST_SIZE))
        train_idx, test_idx = indices[:cut], indices[cut:]

    X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]

    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)
    test_r2 = r2_score(y_test, y_pred) if len(X_test) > 1 else np.nan
    save_permutation_importance(model, X_test, y_test, feature_cols, scoring="r2")

    report = []
    report.append("NITROSATIVE SUSCEPTIBILITY INDEX REPORT")
    report.append("=" * 60)
    report.append("Mode: hierarchical proxy NSI ranking and tree-based sensitivity")
    report.append("")
    report.append("NSI model:")
    for component, weight in COMPONENT_WEIGHTS.items():
        report.append(f"  {component}: {weight:.2f}")
    report.append("")
    report.append("Interpretation:")
    report.append("The NSI_Proxy_Score is a transparent residue-prioritization score, not an experimental label.")
    report.append("The tree regressor is used only to examine nonlinear feature sensitivity to this proxy score.")
    report.append("")
    report.append(f"Total records used: {len(X)}")
    report.append(f"Total groups: {len(unique_groups)}")
    report.append(f"Held-out R2 against proxy NSI: {test_r2:.4f}" if not np.isnan(test_r2) else "Held-out R2 against proxy NSI: undefined")
    report.append(f"Feature columns used: {', '.join(feature_cols)}")
    report.append("")
    report.append("Recommended manuscript wording:")
    report.append("A hierarchical proxy Nitrosative Susceptibility Index was computed from accessibility, chemical microenvironment, evolutionary conservation, and functional-context components. Tree-based modeling was used only for nonlinear sensitivity analysis, while residue-level rankings were reported as the primary output.")
    return "\n".join(report)


# Optional supervised classification using independent labels

def run_classification(df: pd.DataFrame, label_col: str) -> str:
    X, feature_cols, numeric_cols, categorical_cols = build_feature_table(df, label_col=label_col)
    y = pd.to_numeric(df[label_col], errors="coerce").astype("Int64")
    valid = y.notna()

    X = X.loc[valid].copy()
    y = y.loc[valid].astype(int).values
    df_valid = df.loc[valid].copy()
    groups = get_groups(df_valid)

    if len(np.unique(y)) < 2:
        raise ValueError(f"Label column {label_col} contains fewer than two classes.")

    unique_groups = np.unique(groups)
    if len(unique_groups) < 3:
        raise ValueError("At least three groups are recommended for group-aware validation.")

    model = Pipeline([
        ("preprocess", make_preprocessor(numeric_cols, categorical_cols)),
        ("model", make_classifier()),
    ])

    splitter = GroupShuffleSplit(n_splits=1, test_size=TEST_SIZE, random_state=RANDOM_STATE)
    train_idx, test_idx = next(splitter.split(X, y, groups=groups))

    X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]
    groups_train = groups[train_idx]

    n_splits = min(N_SPLITS, len(np.unique(groups_train)))
    gkf = GroupKFold(n_splits=n_splits)
    cv_auc_scores = []
    cv_ap_scores = []

    for train_fold_idx, val_fold_idx in gkf.split(X_train, y_train, groups=groups_train):
        X_fold_train = X_train.iloc[train_fold_idx]
        X_fold_val = X_train.iloc[val_fold_idx]
        y_fold_train = y_train[train_fold_idx]
        y_fold_val = y_train[val_fold_idx]
        if len(np.unique(y_fold_val)) < 2 or len(np.unique(y_fold_train)) < 2:
            continue
        fold_model = Pipeline([
            ("preprocess", make_preprocessor(numeric_cols, categorical_cols)),
            ("model", make_classifier()),
        ])
        fold_model.fit(X_fold_train, y_fold_train)
        fold_proba = fold_model.predict_proba(X_fold_val)[:, 1]
        cv_auc_scores.append(roc_auc_score(y_fold_val, fold_proba))
        cv_ap_scores.append(average_precision_score(y_fold_val, fold_proba))

    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)
    y_proba = model.predict_proba(X_test)[:, 1]

    test_auc = roc_auc_score(y_test, y_proba) if len(np.unique(y_test)) > 1 else np.nan
    test_ap = average_precision_score(y_test, y_proba) if len(np.unique(y_test)) > 1 else np.nan
    save_permutation_importance(model, X_test, y_test, feature_cols, scoring="roc_auc" if len(np.unique(y_test)) > 1 else "accuracy")

    cm = confusion_matrix(y_test, y_pred)
    plt.figure(figsize=(5.2, 4.4))
    plt.imshow(cm, interpolation="nearest")
    plt.title("Group-Held-Out Confusion Matrix")
    plt.xlabel("Predicted label")
    plt.ylabel("True label")
    plt.xticks([0, 1], ["Resistant", "Susceptible"], rotation=30, ha="right")
    plt.yticks([0, 1], ["Resistant", "Susceptible"])
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            plt.text(j, i, str(cm[i, j]), ha="center", va="center")
    plt.tight_layout()
    plt.savefig(PLOT_CONFUSION_MATRIX, dpi=300)
    plt.close()

    if len(np.unique(y_test)) > 1:
        fpr, tpr, _ = roc_curve(y_test, y_proba)
        plt.figure(figsize=(6, 5))
        plt.plot(fpr, tpr, lw=2, label=f"AUC = {test_auc:.3f}")
        plt.plot([0, 1], [0, 1], linestyle="--", lw=1)
        plt.xlabel("False positive rate")
        plt.ylabel("True positive rate")
        plt.title("Group-Held-Out ROC Curve")
        plt.legend(loc="lower right")
        plt.tight_layout()
        plt.savefig(PLOT_ROC, dpi=300)
        plt.close()

        precision, recall, _ = precision_recall_curve(y_test, y_proba)
        plt.figure(figsize=(6, 5))
        plt.plot(recall, precision, lw=2, label=f"AP = {test_ap:.3f}")
        plt.xlabel("Recall")
        plt.ylabel("Precision")
        plt.title("Group-Held-Out Precision-Recall Curve")
        plt.legend(loc="lower left")
        plt.tight_layout()
        plt.savefig(PLOT_PR, dpi=300)
        plt.close()

    report = []
    report.append("NITROSATIVE SUSCEPTIBILITY CLASSIFICATION REPORT")
    report.append("=" * 60)
    report.append("Mode: supervised classification")
    report.append(f"Label column: {label_col}")
    report.append(f"Model: {'XGBoost' if XGBOOST_AVAILABLE else 'RandomForest'}")
    report.append(f"Total labeled records: {len(X)}")
    report.append(f"Total groups: {len(unique_groups)}")
    report.append(f"Training records: {len(X_train)}")
    report.append(f"Held-out test records: {len(X_test)}")
    report.append(f"Feature columns used: {', '.join(feature_cols)}")
    report.append("")
    report.append("Group-aware cross-validation on training data:")
    report.append(f"Mean ROC-AUC: {np.mean(cv_auc_scores):.4f}" if cv_auc_scores else "Mean ROC-AUC: undefined")
    report.append(f"Mean average precision: {np.mean(cv_ap_scores):.4f}" if cv_ap_scores else "Mean average precision: undefined")
    report.append("")
    report.append("Held-out group test performance:")
    report.append(f"ROC-AUC: {test_auc:.4f}" if not np.isnan(test_auc) else "ROC-AUC: undefined")
    report.append(f"Average precision: {test_ap:.4f}" if not np.isnan(test_ap) else "Average precision: undefined")
    report.append("")
    report.append(classification_report(y_test, y_pred, zero_division=0))
    report.append("")
    report.append("Important note: metrics are valid only if the label column represents independent curated or experimental labels.")
    return "\n".join(report)


