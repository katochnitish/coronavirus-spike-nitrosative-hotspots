    if "Residue_Label" not in ranked.columns:
        ranked["Residue_Label"] = ranked.apply(residue_label_from_row, axis=1)

    aggregation = {
        "NSI_Proxy_Score": ["mean", "max", "std", "count"],
        "Accessibility_Component": "mean",
        "Chemistry_Component": "mean",
        "Evolution_Component": "mean",
        "Functional_Context_Component": "mean",
    }
    optional_first = ["Reference_AA", "Residue_Type", "Sequence_Position", "Domain"]
    for col in optional_first:
        if col in ranked.columns:
            aggregation[col] = "first"
    if "Conservation_Frequency" in ranked.columns:
        aggregation["Conservation_Frequency"] = "mean"
    if "Shannon_Entropy" in ranked.columns:
        aggregation["Shannon_Entropy"] = "mean"

    residue_ranked = ranked.groupby("Residue_Label", dropna=False).agg(aggregation)
    residue_ranked.columns = ["_".join(col).strip("_") if isinstance(col, tuple) else col for col in residue_ranked.columns]
    residue_ranked = residue_ranked.rename(columns={
        "NSI_Proxy_Score_mean": "Mean_NSI",
        "NSI_Proxy_Score_max": "Max_NSI",
        "NSI_Proxy_Score_std": "SD_NSI",
        "NSI_Proxy_Score_count": "Variant_Record_Count",
    })
    residue_ranked = residue_ranked.reset_index()
    residue_ranked["Residue_Level_Rank"] = residue_ranked["Mean_NSI"].rank(ascending=False, method="dense").astype(int)
    residue_ranked = residue_ranked.sort_values(["Mean_NSI", "Max_NSI"], ascending=False)
    residue_ranked.to_csv(OUTPUT_RESIDUE_RANKING, index=False)

    top_residue = residue_ranked.head(TOP_N_PLOT).copy()
    plt.figure(figsize=(8.5, max(5, len(top_residue) * 0.30)))
    plt.barh(top_residue["Residue_Label"].iloc[::-1], top_residue["Mean_NSI"].iloc[::-1], edgecolor="black")
    plt.xlabel("Mean proxy NSI across variants")
    plt.ylabel("Wuhan-coordinate residue")
    plt.title(f"Top {len(top_residue)} Residue-Level Candidate Sites")
    plt.tight_layout()
    plt.savefig(PLOT_TOP_RESIDUES, dpi=300)
    plt.close()

    # Component contribution summary.
