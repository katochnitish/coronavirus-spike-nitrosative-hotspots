# Core NSI calculation using hierarchical biological model

def compute_hierarchical_nsi(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()

    # -------------------------------------------------------------------------
    # Accessibility component
    # -------------------------------------------------------------------------
    relative_sasa_col = first_existing(out, ["Relative_SASA"])
    true_sasa_col = first_existing(out, ["True_SASA_A2", "True_SASA"])
    exposure_proxy_col = first_existing(out, ["Packing_Density_Exposure_Proxy", "Solvent_Exposure_Proxy"])
    residue_depth_col = first_existing(out, ["Residue_Depth_Proxy_A"])

    sasa_score = None
    if relative_sasa_col:
        sasa_score = minmax(out[relative_sasa_col])
    elif true_sasa_col:
        sasa_score = minmax(out[true_sasa_col])

    exposure_proxy_score = minmax(out[exposure_proxy_col]) if exposure_proxy_col else None
    depth_score = minmax(out[residue_depth_col]) if residue_depth_col else None

    # Accessibility score from exposure and structure
    out["Accessibility_Component"] = safe_mean(
        [sasa_score, exposure_proxy_score, depth_score],
        index=out.index,
    )

    # -------------------------------------------------------------------------
    # Chemistry component
    # -------------------------------------------------------------------------
    elec_col = first_existing(out, ["Electrostatic_Balance_8A", "Weighted_Electrostatic_Potential"])
    elec = numeric_series(out, elec_col, default=0.0).fillna(0.0)
    residue_type = out.get("Residue_Type", pd.Series("", index=out.index)).astype(str).str.lower()
    observed_aa = out.get("Observed_AA", pd.Series("", index=out.index)).astype(str)
    cys_mask = residue_type.str.contains("cys") | observed_aa.eq("C")
    elec_for_cys = minmax(elec)
    elec_for_tyr = minmax(elec.abs())
    electrostatic_score = pd.Series(np.where(cys_mask, elec_for_cys, elec_for_tyr), index=out.index)

    hydrophobic_score = minmax(numeric_series(out, first_existing(out, ["Hydrophobic_Count_8A"])))
    polar_score = minmax(numeric_series(out, first_existing(out, ["Polar_Count_8A"])))
    aromatic_score = minmax(numeric_series(out, first_existing(out, ["Aromatic_Count_8A"])))
    sulfur_score = minmax(numeric_series(out, first_existing(out, ["Sulfur_Count_8A"])))

    if "Disulfide_Bonded" in out.columns:
        disulfide = numeric_series(out, "Disulfide_Bonded", default=0.0).fillna(0.0).clip(0, 1)
        free_cys_score = 1.0 - disulfide
        non_cys_score = pd.Series(1.0, index=out.index)
        disulfide_adjusted_score = pd.Series(np.where(cys_mask, free_cys_score, non_cys_score), index=out.index)
    else:
        disulfide_adjusted_score = pd.Series(1.0, index=out.index)

    # Chemical environment contribution
    out["Chemistry_Component"] = safe_mean(
        [
            electrostatic_score,
            hydrophobic_score,
            polar_score,
            aromatic_score,
            sulfur_score,
            disulfide_adjusted_score,
        ],
        index=out.index,
    )

    # -------------------------------------------------------------------------
    # Evolution component
    # -------------------------------------------------------------------------
    conservation_col = first_existing(out, ["Conservation_Frequency", "Target_Retention_Frequency"])
    entropy_col = first_existing(out, ["Shannon_Entropy"])

    conservation_score = minmax(numeric_series(out, conservation_col)) if conservation_col else None
    entropy_score = minmax(numeric_series(out, entropy_col)) if entropy_col else None

    # Conserved residues support functional relevance; entropy supports variant-specific vulnerability.
    # Evolutionary conservation and variability
    out["Evolution_Component"] = safe_mean(
        [conservation_score, entropy_score],
        index=out.index,
    )

    # -------------------------------------------------------------------------
    # Functional context component
    # -------------------------------------------------------------------------
    ace2_col = first_existing(out, ["Nearest_ACE2_Interface_Distance_A", "Nearest_ACE2_Interface_Distance", "Interface_Proximity_Index"])
    glycan_col = first_existing(out, ["Nearest_Glycan_Sequon_Distance_A", "Nearest_Glycan_Distance"])

    if ace2_col is None:
        ace2_score = None
    elif ace2_col == "Interface_Proximity_Index":
        ace2_score = minmax(out[ace2_col])
    else:
        ace2_score = minmax(out[ace2_col], invert=True)

    # A higher distance from glycan sequons is interpreted as lower shielding.
    glycan_score = minmax(out[glycan_col]) if glycan_col else None

    if "Is_RBM" in out.columns:
        rbm_score = numeric_series(out, "Is_RBM", default=0.0).fillna(0.0).clip(0, 1)
    elif "Domain" in out.columns:
        rbm_score = out["Domain"].astype(str).str.contains("RBM", case=False, na=False).astype(float)
    else:
        rbm_score = None

    if "Is_RBD" in out.columns:
        rbd_score = 0.5 * numeric_series(out, "Is_RBD", default=0.0).fillna(0.0).clip(0, 1)
    elif "Domain" in out.columns:
        rbd_score = 0.5 * out["Domain"].astype(str).str.contains("RBD|RBM", case=False, regex=True, na=False).astype(float)
    else:
        rbd_score = None

    # Functional relevance (ACE2, glycan, domain)
    out["Functional_Context_Component"] = safe_mean(
        [ace2_score, glycan_score, rbm_score, rbd_score],
        index=out.index,
    )

    # -------------------------------------------------------------------------
    # Final NSI score
    # -------------------------------------------------------------------------
    # Final weighted NSI score
    out["NSI_Proxy_Score"] = sum(
        COMPONENT_WEIGHTS[component] * out[component]
        for component in COMPONENT_WEIGHTS
    )

    out["NSI_Rank"] = out["NSI_Proxy_Score"].rank(ascending=False, method="dense").astype(int)

    # Keep a compact component score output table.
    component_cols = [
        "Variant_ID", "Residue_Label", "Reference_AA", "Observed_AA", "Residue_Type",
        "Sequence_Position", "Domain", "NSI_Proxy_Score", "NSI_Rank",
        "Accessibility_Component", "Chemistry_Component", "Evolution_Component", "Functional_Context_Component",
    ]
    available_component_cols = [col for col in component_cols if col in out.columns]
    out[available_component_cols].to_csv(OUTPUT_COMPONENTS, index=False)

    return out


