    plt.figure(figsize=(7, 4.5))
    plt.hist(ranked["NSI_Proxy_Score"], bins=30, edgecolor="black")
    p95 = ranked["NSI_Proxy_Score"].quantile(0.95)
    median = ranked["NSI_Proxy_Score"].median()
    plt.axvline(median, linestyle="--", linewidth=1.5, label=f"Median = {median:.3f}")
    plt.axvline(p95, linestyle=":", linewidth=2.0, label=f"95th percentile = {p95:.3f}")
    plt.xlabel("Proxy Nitrosative Susceptibility Index")
    plt.ylabel("Candidate site count")
    plt.title("Distribution of Hierarchical Proxy NSI Scores")
    plt.legend()
    plt.tight_layout()
    plt.savefig(PLOT_NSI_DISTRIBUTION, dpi=300)
    plt.close()

